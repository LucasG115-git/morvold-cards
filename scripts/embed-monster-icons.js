/**
 * Reads SVG files from assets/icons/ and writes js/monster-icon-data.js
 * with data URIs so icons work when the page is opened via file:// (no CORS).
 * Run from the generator folder: node scripts/embed-monster-icons.js
 */
const fs = require('fs');
const path = require('path');

const ICON_NAMES = [
  'cr', 'pb', 'speed', 'skills', 'saving_throws', 'resistances',
  'vulnerabilities', 'damage_immunities', 'condition_immunities', 'languages', 'senses'
];

const generatorDir = path.resolve(__dirname, '..');
const iconsDir = path.join(generatorDir, 'assets', 'icons');
const outPath = path.join(generatorDir, 'js', 'monster-icon-data.js');

const data = {};
for (const name of ICON_NAMES) {
  const file = path.join(iconsDir, name + '.svg');
  try {
    const content = fs.readFileSync(file, 'utf8');
    const dataUri = 'data:image/svg+xml,' + encodeURIComponent(content);
    data[name] = dataUri;
  } catch (e) {
    console.warn('Skip ' + name + '.svg: ' + (e.code === 'ENOENT' ? 'file not found' : e.message));
  }
}

const js = '/* Generated by scripts/embed-monster-icons.js - do not edit */\n' +
  'window.MONSTER_ICON_DATA = ' + JSON.stringify(data) + ';\n';

fs.writeFileSync(outPath, js, 'utf8');
console.log('Wrote ' + outPath + ' with ' + Object.keys(data).length + ' icons.');
